#!/usr/bin/env node
// Scans games/*/game.json, validates each, and writes games.js (window.GAMES = [...])
// for the arcade front page. Run after adding or editing a game: `npm run gallery`.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const gamesDir = join(root, 'games');

const REQUIRED = ['title', 'tagline', 'number', 'created', 'genres', 'color'];

export function loadGames({ warn = console.warn, includeDrafts = false } = {}) {
  const games = [];
  for (const slug of readdirSync(gamesDir, { withFileTypes: true })) {
    if (!slug.isDirectory() || slug.name.startsWith('.') || slug.name.startsWith('_')) continue;
    const dir = join(gamesDir, slug.name);
    const metaPath = join(dir, 'game.json');
    if (!existsSync(metaPath)) {
      warn(`skip games/${slug.name}: no game.json`);
      continue;
    }
    let meta;
    try {
      meta = JSON.parse(readFileSync(metaPath, 'utf8'));
    } catch (e) {
      warn(`skip games/${slug.name}: game.json is not valid JSON (${e.message})`);
      continue;
    }
    const missing = REQUIRED.filter((k) => meta[k] === undefined || meta[k] === '');
    if (missing.length) warn(`games/${slug.name}/game.json is missing: ${missing.join(', ')}`);
    if (!existsSync(join(dir, 'index.html'))) warn(`games/${slug.name} has no index.html`);
    if (meta.draft && !includeDrafts) continue;
    games.push({
      slug: slug.name,
      href: `games/${slug.name}/`,
      thumb: ['thumb.jpg', 'thumb.png'].map((f) => existsSync(join(dir, f)) && `games/${slug.name}/${f}`).find(Boolean) || null,
      ...meta,
    });
  }
  return games.sort((a, b) => (a.number ?? 0) - (b.number ?? 0));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const games = loadGames();
  const body = `// Generated by scripts/build-gallery.mjs — do not edit by hand.\nwindow.GAMES = ${JSON.stringify(games, null, 2)};\n`;
  writeFileSync(join(root, 'games.js'), body);
  console.log(`games.js: ${games.length} game(s) — ${games.map((g) => g.slug).join(', ') || 'none yet'}`);
}
