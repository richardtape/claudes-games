#!/usr/bin/env node
// Build the hole bank: generate holes per tier, keep those the solver can ace and the bots
// can finish, set par from the casual bot, and write js/bank.js.
//
// Resumable: every accepted hole is appended to .tmp/comet-bank/t<tier>.jsonl as soon as it
// is made, so a run that is stopped (or a busy machine) loses nothing. Run it again to carry
// on; js/bank.js is written once every tier has --per holes.
//
//   node games/comet-cup/tools/bank.mjs              # 40 holes per tier
//   node games/comet-cup/tools/bank.mjs --per 12     # quick small bank
//   node games/comet-cup/tools/bank.mjs --tiers 3,4  # only some tiers this run
//   node games/comet-cup/tools/bank.mjs --fresh      # forget the saved progress first
//   node games/comet-cup/tools/bank.mjs --repar      # only recompute par from the stored stats
import { writeFileSync, readFileSync, appendFileSync, mkdirSync, existsSync, rmSync } from 'node:fs';
import { createRng } from '../../../shared/rng.js';
import { generateHole, roundHole, holeName } from '../js/gen.js';
import { prepareWorld } from '../js/engine.js';
import { findAce, playHole, SKILLS } from '../js/bot.js';

const args = process.argv.slice(2);
const opt = (name, d) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 ? args[i + 1] : d;
};
const PER = Number(opt('per', 40));
const SEED = opt('seed', 'comet-cup-bank-2');
const TIERS = opt('tiers', '1,2,3,4').split(',').map(Number);
const OUT = new URL('../js/bank.js', import.meta.url);
const WORK = new URL('../../../.tmp/comet-bank/', import.meta.url);

// The easiest acceptable ace rate (share of a 1° × 5% grid that holes out) per tier: above
// this the hole is a gimme. Casual-bot strokes must stay between minMean and maxMean.
const RULES = {
  1: { maxRate: 0.014, maxMean: 3.0, minMean: 1.6 },
  2: { maxRate: 0.01, maxMean: 3.7, minMean: 1.9 },
  3: { maxRate: 0.008, maxMean: 4.3, minMean: 2.1 },
  4: { maxRate: 0.007, maxMean: 4.7, minMean: 2.3 },
};
const CASUAL_RUNS = 6;
const GOOD_RUNS = 2;
/**
 * Par from the casual bot's average strokes. The bots know exactly where every shot goes;
 * a person sees only the dotted start, so par gets 0.6 of a stroke on top (first-time play
 * by Claude ran about half a stroke over the bot average).
 */
const parFor = (mean) => Math.max(2, Math.min(5, Math.round(mean + 0.6)));

function write(bank, seed) {
  const body = `// Generated by tools/bank.mjs (seed ${JSON.stringify(seed)}); do not edit by hand.\n` +
    `// Each hole was aced by the solver from its tee; par comes from a casual bot's average.\n` +
    `export const BANK = [\n${bank.map((h) => '  ' + JSON.stringify(h)).join(',\n')}\n];\n`;
  writeFileSync(OUT, body);
  console.log(`wrote ${OUT.pathname} (${bank.length} holes)`);
}

if (args.includes('--repar')) {
  const { BANK } = await import(OUT.href);
  const pars = {};
  for (const h of BANK) {
    h.par = parFor(h.stats.casual);
    pars[`t${h.tier} par ${h.par}`] = (pars[`t${h.tier} par ${h.par}`] || 0) + 1;
  }
  console.log('pars', pars);
  write(BANK.map(({ star, ...h }) => h), SEED);
  process.exit(0);
}

if (args.includes('--fresh')) rmSync(WORK, { recursive: true, force: true });
mkdirSync(WORK, { recursive: true });
const fileFor = (tier) => new URL(`t${tier}.jsonl`, WORK);
const load = (tier) =>
  existsSync(fileFor(tier))
    ? readFileSync(fileFor(tier), 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l))
    : [];

const rejects = {};
const t0 = performance.now();
for (const tier of TIERS) {
  const rule = RULES[tier];
  const have = load(tier);
  let made = have.length;
  // Seeded by where this run starts, so a resumed run is still reproducible.
  const rng = createRng(`${SEED}:t${tier}:from${made}`);
  let tries = 0;
  while (made < PER && tries < PER * 40) {
    tries++;
    const hole = roundHole(generateHole(rng, tier));
    hole.par = 9; // provisional: bots must not get picked up while we measure
    const w = prepareWorld(hole);
    const a = findAce(w, hole.tee.x, hole.tee.y);
    const why = !a.ace ? 'no ace' : a.rate > rule.maxRate ? 'gimme' : null;
    if (why) {
      rejects[why] = (rejects[why] || 0) + 1;
      continue;
    }
    let sum = 0;
    let n = 0;
    let hopeless = false;
    for (; n < CASUAL_RUNS; n++) {
      sum += playHole(hole, SKILLS.casual, rng);
      // Even if every remaining run were an ace, the mean would be too high: stop early.
      if ((sum + (CASUAL_RUNS - n - 1)) / CASUAL_RUNS > rule.maxMean) {
        hopeless = true;
        break;
      }
    }
    const mean = sum / CASUAL_RUNS;
    if (hopeless || mean > rule.maxMean || mean < rule.minMean) {
      const k = hopeless || mean > rule.maxMean ? 'too hard' : 'too easy';
      rejects[k] = (rejects[k] || 0) + 1;
      continue;
    }
    let good = 0;
    for (let i = 0; i < GOOD_RUNS; i++) good += playHole(hole, SKILLS.good, rng);
    const h = {
      id: `${tier}-${String(made + 1).padStart(3, '0')}`,
      tier,
      par: parFor(mean),
      name: holeName(rng, hole.kind),
      kind: hole.kind,
      extra: hole.extra,
      bodies: hole.bodies,
      tee: hole.tee,
      cup: hole.cup,
      ace: { vx: a.ace.vx, vy: a.ace.vy },
      stats: { rate: +a.rate.toFixed(5), casual: +mean.toFixed(2), good: +(good / GOOD_RUNS).toFixed(2) },
    };
    appendFileSync(fileFor(tier), JSON.stringify(h) + '\n');
    made++;
    console.log(`tier ${tier}: ${made}/${PER} (${tries} tried, ${((performance.now() - t0) / 1000).toFixed(0)} s)`);
  }
}
console.log('rejects', rejects);

const all = [1, 2, 3, 4].map((t) => load(t).slice(0, PER));
const short = all.map((l, i) => (l.length < PER ? `tier ${i + 1} has ${l.length}` : null)).filter(Boolean);
if (short.length) {
  console.log(`not writing bank.js yet: ${short.join(', ')} of ${PER}. Run again to carry on.`);
  process.exit(0);
}
const bank = all.flat();
const pars = {};
const kinds = {};
for (const h of bank) {
  pars[`t${h.tier} par ${h.par}`] = (pars[`t${h.tier} par ${h.par}`] || 0) + 1;
  kinds[h.kind] = (kinds[h.kind] || 0) + 1;
}
console.log('pars', pars);
console.log('kinds', kinds);
write(bank, SEED);
