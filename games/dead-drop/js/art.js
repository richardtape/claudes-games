// Dead Drop art: flat cut-paper silhouettes after Saul Bass's 1960s title sequences.
// Every shape is a polygon whose corners are nudged a little off true (seeded per drawing,
// so the output is stable), like paper cut by hand. Main shapes inherit fill="currentColor";
// accent shapes carry class="ac" for the game's CSS to colour. Cut-outs are reversed
// subpaths (holes) under the default nonzero rule, so whatever lies behind shows through.

let seed = 1;
let J = 0.5;
const rnd = () => (seed = (seed * 16807) % 2147483647) / 2147483647;
const begin = (key, j) => {
  seed = 7;
  for (const c of key) seed = (seed * 31 + c.charCodeAt(0)) % 2147483647 || 1;
  J = j;
};
const RAD = Math.PI / 180;
const fx = (v) => Math.round(v * 10) / 10;

/** Give a flat [x,y,...] polygon positive (want=1) or negative winding. */
function orient(p, want) {
  let a = 0;
  const n = p.length;
  for (let i = 0; i < n; i += 2) {
    const j = (i + 2) % n;
    a += p[i] * p[j + 1] - p[j] * p[i + 1];
  }
  if (a > 0 === want > 0) return p;
  const q = [];
  for (let i = n - 2; i >= 0; i -= 2) q.push(p[i], p[i + 1]);
  return q;
}
const sub = (p) => (p.length < 6 ? '' : 'M' + orient(p, p.h ? -1 : 1).map((v) => fx(v + (rnd() - 0.5) * 2 * J)).join(' ') + 'Z');
const flat = (list) => list.flatMap((x) => (Array.isArray(x[0]) ? flat(x) : [x]));
const ink = (...s) => `<path d="${flat(s).map(sub).join('')}"/>`;
const acc = (...s) => `<path class="ac" d="${flat(s).map(sub).join('')}"/>`;
/** Mark a polygon as a hole (cut out of whatever it sits inside). */
const H = (p) => Object.assign(p.slice(), { h: 1 });
const keep = (p, q) => (p.h ? H(q) : q);

