/** A flat-topped crenellated edge from x0 to x1 at height y (merlons h tall). */
const cren = (x0, x1, y, h, n) => {
  const w = (x1 - x0) / n;
  const p = [x0, y];
  for (let i = 0; i < n; i++) {
    const a = x0 + i * w;
    p.push(a, y - h, a + w * 0.55, y - h, a + w * 0.55, y, a + w, y);
  }
  return p;
};
