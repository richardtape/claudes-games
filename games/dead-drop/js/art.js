const Q = (x, y, w, h) => [x, y, x + w, y, x + w, y + h, x, y + h];
/** Hand-cut ellipse: n corners, each a little off. */
const E = (cx, cy, rx, ry = rx, n = 13, rot = 0) => {
  const p = [];
  const c = Math.cos(rot * RAD);
  const s = Math.sin(rot * RAD);
  const o = rnd();
  for (let k = 0; k < n; k++) {
    const a = ((k + o + (rnd() - 0.5) * 0.35) / n) * 2 * Math.PI;
    const f = 1 + (rnd() - 0.5) * 0.05;
    const x = Math.cos(a) * rx * f;
    const y = Math.sin(a) * ry * f;
    p.push(cx + x * c - y * s, cy + x * s + y * c);
  }
  return p;
};
/** Points along an elliptical arc, degrees (0 = right, 90 = down, 270 = up). */
const A = (cx, cy, rx, ry, a0, a1, n = 8) => {
  const p = [];
  for (let k = 0; k <= n; k++) {
    const a = (a0 + ((a1 - a0) * k) / n) * RAD;
    p.push(cx + Math.cos(a) * rx, cy + Math.sin(a) * ry);
  }
  return p;
};
/** A strip along a quadratic curve, width w0 tapering to w1: fronds, wires, arms. */
const B = (x0, y0, cx, cy, x1, y1, w0, w1 = 0, n = 6) => {
  const l = [];
  const r = [];
  for (let k = 0; k <= n; k++) {
    const t = k / n;
    const u = 1 - t;
    const x = u * u * x0 + 2 * u * t * cx + t * t * x1;
    const y = u * u * y0 + 2 * u * t * cy + t * t * y1;
    const dx = 2 * u * (cx - x0) + 2 * t * (x1 - cx);
    const dy = 2 * u * (cy - y0) + 2 * t * (y1 - cy);
    const m = Math.hypot(dx, dy) || 1;
    const w = (w0 + (w1 - w0) * t) / 2;
    l.push(x - (dy / m) * w, y + (dx / m) * w);
    r.unshift(x + (dy / m) * w, y - (dx / m) * w);
  }
  return l.concat(r);
};
/** A straight bar from one point to another. */
const L = (x0, y0, x1, y1, w0, w1 = w0) => B(x0, y0, (x0 + x1) / 2, (y0 + y1) / 2, x1, y1, w0, w1, 1);
/** Rotate (deg) and scale about the origin, then move. */
const T = (p, dx, dy, s = 1, rot = 0, sy = s) => {
  const c = Math.cos(rot * RAD);
  const sn = Math.sin(rot * RAD);
  const q = [];
  for (let i = 0; i < p.length; i += 2) {
    const x = p[i] * s;
    const y = p[i + 1] * sy;
    q.push(dx + x * c - y * sn, dy + x * sn + y * c);
  }
  return keep(p, q);
};
const mir = (p, c = 50) => keep(p, p.map((v, i) => (i % 2 ? v : 2 * c - v)));
/** Keep the part of a polygon left of the line a->b, pushed off it by `off`. */
function clip(p, ax, ay, bx, by, off) {
  let nx = ay - by;
  let ny = bx - ax;
  const m = Math.hypot(nx, ny);
  nx /= m;
  ny /= m;
  const f = (i) => (p[i] - ax) * nx + (p[i + 1] - ay) * ny - off;
  const out = [];
  for (let i = 0; i < p.length; i += 2) {
    const j = (i + 2) % p.length;
    const fi = f(i);
    const fj = f(j);
    if (fi >= 0) out.push(p[i], p[i + 1]);
    if (fi >= 0 !== fj >= 0) {
      const t = fi / (fi - fj);
      out.push(p[i] + (p[j] - p[i]) * t, p[i + 1] + (p[j + 1] - p[i + 1]) * t);
    }
  }
  return keep(p, out);
}
/** Scissor cut: split a polygon along a line, leaving a gap g between the pieces. */
const cut = (p, ax, ay, bx, by, g = 3) => [clip(p, ax, ay, bx, by, g / 2), clip(p, bx, by, ax, ay, g / 2)];
const cuts = (shapes, lines, g) => lines.reduce((ps, l) => ps.flatMap((q) => cut(q, ...l, g)), flat(shapes));
/** Thicken a polyline [x,y,...] to an even width w, with mitred corners. */
const strip = (pts, w) => {
  const n = pts.length / 2;
  const l = [];
  const r = [];
  const dir = (i) => {
    const dx = pts[2 * i + 2] - pts[2 * i];
    const dy = pts[2 * i + 3] - pts[2 * i + 1];
    const m = Math.hypot(dx, dy) || 1;
    return [-dy / m, dx / m];
  };
  for (let i = 0; i < n; i++) {
    const a = dir(Math.max(0, i - 1));
    const b = dir(Math.min(n - 2, i));
    let mx = a[0] + b[0];
    let my = a[1] + b[1];
    const m = Math.hypot(mx, my) || 1;
    mx /= m;
    my /= m;
    const k = Math.min(w, w / 2 / Math.max(0.2, mx * b[0] + my * b[1]));
    l.push(pts[2 * i] + mx * k, pts[2 * i + 1] + my * k);
    r.unshift(pts[2 * i] - mx * k, pts[2 * i + 1] - my * k);
  }
  return l.concat(r);
};
/** Zigzag band along an arc (radio waves). */
const zig = (cx, cy, r, a0, a1, n, amp, w) =>
  strip(Array.from({ length: n + 1 }, (_, k) => {
    const a = (a0 + ((a1 - a0) * k) / n) * RAD;
    const rr = r + (k % 2 ? amp : -amp) * (k && k < n ? 1 : 0.4);
    return [cx + Math.cos(a) * rr, cy + Math.sin(a) * rr];
  }).flat(), w);
